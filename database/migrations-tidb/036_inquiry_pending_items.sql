CREATE TABLE IF NOT EXISTS inquiry_pending_items (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  public_id VARCHAR(191) NOT NULL,
  inquiry_id BIGINT NOT NULL,
  source_message_id BIGINT NOT NULL,
  original_text TEXT NOT NULL,
  source_field VARCHAR(64) NOT NULL,
  original_hash CHAR(64) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'pending',
  resolution_message_id BIGINT NULL,
  resolved_version_id BIGINT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved_at DATETIME NULL,
  UNIQUE KEY uq_inquiry_pending_public_id (public_id),
  UNIQUE KEY uq_inquiry_pending_source (inquiry_id,source_message_id,source_field,original_hash),
  KEY idx_inquiry_pending_items_status (inquiry_id,status),
  FOREIGN KEY (inquiry_id) REFERENCES inquiries(id),
  FOREIGN KEY (source_message_id) REFERENCES messages(id),
  FOREIGN KEY (resolution_message_id) REFERENCES messages(id),
  FOREIGN KEY (resolved_version_id) REFERENCES intention_versions(id),
  CHECK (status IN ('pending','included','withdrawn')),
  CHECK ((status = 'pending') = (resolved_at IS NULL)),
  CHECK ((status = 'withdrawn') = (resolution_message_id IS NOT NULL)),
  CHECK ((status = 'included') = (resolved_version_id IS NOT NULL))
);
